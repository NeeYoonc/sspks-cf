#!/usr/bin/env python3
"""Generate src/models.js from data/synology_models.yaml.

The YAML file (taken from sspks-imnks) has a strictly fixed three-level shape:

    <family>:
        <arch>:
            - <model>
            - <model>

No anchors, no quotes, no inline comments are used, so a tiny indentation
parser is enough and keeps the project dependency free.

Usage: python tools/gen_models.py [--check]
  --check  exit 1 when the committed src/models.js is out of date.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
YAML = ROOT / "data" / "synology_models.yaml"
TARGET = ROOT / "src" / "models.js"

HEADER = """\
// Generated by tools/gen_models.py from data/synology_models.yaml.
// Do not edit by hand; run `python tools/gen_models.py` to regenerate.
"""


def parse_models(text: str) -> dict[str, dict[str, list[str]]]:
    families: dict[str, dict[str, list[str]]] = {}
    family: str | None = None
    arch: str | None = None
    for raw in text.splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        indent = len(raw) - len(raw.lstrip(" "))
        item = raw.strip()
        if indent == 0:
            if not item.endswith(":"):
                raise ValueError(f"unexpected top-level line: {raw!r}")
            family = item[:-1].strip()
            families[family] = {}
            arch = None
        elif indent == 4:
            if family is None or not item.endswith(":"):
                raise ValueError(f"unexpected architecture line: {raw!r}")
            arch = item[:-1].strip()
            families[family][arch] = []
        elif indent >= 8 and item.startswith("- "):
            if family is None or arch is None:
                raise ValueError(f"model without architecture: {raw!r}")
            families[family][arch].append(item[2:].strip())
        else:
            raise ValueError(f"unexpected line: {raw!r}")
    if not families:
        raise ValueError("no families parsed from synology_models.yaml")
    return families


def build() -> str:
    families = parse_models(YAML.read_text(encoding="utf-8"))

    arch_to_family: dict[str, str] = {}
    for family, arches in families.items():
        for arch in arches:
            arch_to_family[arch] = family

    known = sorted(set(arch_to_family) | set(families), key=str.lower)

    out = [HEADER, "export const FAMILIES = ", json.dumps(families, ensure_ascii=False, indent=2), ";\n\n"]
    out += ["export const ARCH_TO_FAMILY = ", json.dumps(arch_to_family, ensure_ascii=False, indent=2), ";\n\n"]
    out += ["export const KNOWN_ARCHITECTURES = ", json.dumps(known, ensure_ascii=False, indent=2), ";\n\n"]
    out.append(
        "/**\n"
        " * Resolve the architecture family used by PackageFilter::setArchitectureFilter.\n"
        " * Unknown architectures fall back to themselves, mirroring the PHP source.\n"
        " */\n"
        "export function familyOf(arch) {\n"
        "  return ARCH_TO_FAMILY[arch] || arch;\n"
        "}\n\n"
        "export function isKnownArchitecture(arch) {\n"
        "  return Object.prototype.hasOwnProperty.call(ARCH_TO_FAMILY, arch) || Object.prototype.hasOwnProperty.call(FAMILIES, arch);\n"
        "}\n"
    )
    return "".join(out)


def main() -> int:
    generated = build()
    if "--check" in sys.argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != generated:
            print("src/models.js is out of date; run python tools/gen_models.py", file=sys.stderr)
            return 1
        print("src/models.js is up to date")
        return 0
    TARGET.write_text(generated, encoding="utf-8", newline="\n")
    families = parse_models(YAML.read_text(encoding="utf-8"))
    arches = sum(len(v) for v in families.values())
    models = sum(len(m) for v in families.values() for m in v.values())
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(families)} families, {arches} architectures, {models} models")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
